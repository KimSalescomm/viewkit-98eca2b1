export const ALL_BRANCHES: string[] = BRANCH_GROUPS.flatMap((g) => g.branches);

export const getManagerByBranch = (branch: string): string | null => {
  const norm = (branch || "").trim();
  for (const g of BRANCH_GROUPS) {
    if (g.branches.includes(norm)) return g.manager;
  }
  return null;
};

// 전문점(베스트샵 팀) 여부 판정 — 백화점영업담당은 하이프라자이므로 제외
export const isSpecialtyManager = (manager: string | null | undefined): boolean => {
  if (!manager) return false;
  return manager.endsWith("팀");
};

// 현재 매장 카테고리 라벨: 전문점은 "전문점", 그 외는 담당명 그대로
export const getStoreCategoryLabel = (branch: string): string | null => {
  const m = getManagerByBranch(branch);
  if (!m) return null;
  return isSpecialtyManager(m) ? "전문점" : `${m} 담당`;
};

/** 프론트엔드 표시용: '베스트샵' 접두어 제거 */
export const cleanBranchName = (branch: string): string => {
  if (!branch) return branch;
  return branch.replace(/^베스트샵\s*/, "");
};


