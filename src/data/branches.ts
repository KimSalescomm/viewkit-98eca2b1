// 거래선명으로 매장명 조회 (직접 입력 시 자동 매칭)
export const resolveBranchByDealer = (input: string): string | null => {
  const key = (input || "").trim();
  if (!key) return null;
  if (DEALER_TO_BRANCH_MAP[key]) return DEALER_TO_BRANCH_MAP[key];
  // 공백 무시 매칭
  const norm = key.replace(/\s+/g, "");
  for (const [dealer, branch] of Object.entries(DEALER_TO_BRANCH_MAP)) {
    if (dealer.replace(/\s+/g, "") === norm) return branch;
  }
  return null;
};

export const getBranchCode = (name: string): string | null => {
  const key = (name || "").trim();
  return BRANCH_CODE_MAP[key] ?? null;
};

export const getBranchNameByCode = (code: string): string | null => {
  const c = (code || "").trim().toUpperCase();
  const entry = Object.entries(BRANCH_CODE_MAP).find(([, v]) => v === c);
  return entry ? entry[0] : null;
};

